export const strings = (lang: string): Strings => (lang === "en" ? en : zh);

/** A relative time with the full time for the tooltip. */
export function relative(iso: string, lang: string, now = Date.now()): string {
  const s = (Date.parse(iso) - now) / 1000;
  const abs = Math.abs(s);
  if (abs < 45) return strings(lang).justNow;
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: "auto" });
  for (const [unit, n] of [["year", 31536000], ["month", 2592000], ["day", 86400], ["hour", 3600], ["minute", 60]] as const) {
    if (abs >= n) return rtf.format(Math.round(s / n), unit);
  }
  return rtf.format(Math.round(s / 60), "minute");
}
